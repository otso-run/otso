import { existsSync, readdirSync } from 'node:fs';
import { appendFile, readFile } from 'node:fs/promises';
import { parse, stringify } from 'smol-toml';
import { join } from 'node:path';
import { getConfigDir, getSourcesDir, getSourcesTomlPath } from './paths.js';

/**
 * Reads and (minimally) edits data/config/sources.toml, the indexer's config.
 * The repo file is never edited; personal additions go to sources.local.toml.
 */

export interface TomlSource {
  name: string;
  enabled?: boolean;
  db_path?: string;
  category?: string;
  /** A template for <name>-<device> sources, one per Mac (see Connector.perDevice). */
  per_device?: boolean;
  queries?: unknown[];
}

export interface SourcesToml {
  defaults?: { data_dir?: string; schema_version?: string };
  sources?: TomlSource[];
}

/**
 * Personal sources (e.g. one per Twitter handle) never go in the repo's
 * sources.toml. They live in ~/.otso/config/sources.local.toml, which is
 * merged in when reading and when running the indexer.
 */
export function getLocalSourcesPath(): string {
  return join(getConfigDir(), 'sources.local.toml');
}

async function readOne(path: string): Promise<SourcesToml> {
  if (!existsSync(path)) return {};
  return parse(await readFile(path, 'utf8')) as unknown as SourcesToml;
}

export async function readSourcesToml(path = getSourcesTomlPath()): Promise<SourcesToml> {
  const base = await readOne(path);
  const local = await readOne(getLocalSourcesPath());
  return { ...base, sources: [...(base.sources ?? []), ...(local.sources ?? [])] };
}

export async function hasSource(name: string, path = getSourcesTomlPath()): Promise<boolean> {
  const cfg = await readSourcesToml(path);
  return (cfg.sources ?? []).some((s) => s.name === name);
}

/** Add a personal [[sources]] block to sources.local.toml if the name is new. */
export async function ensureSourceBlock(name: string, block: string): Promise<boolean> {
  if (await hasSource(name)) return false;
  const { mkdir, chmod } = await import('node:fs/promises');
  await mkdir(getConfigDir(), { recursive: true, mode: 0o700 });
  const path = getLocalSourcesPath();
  await appendFile(path, `\n${block.trim()}\n`, { mode: 0o600 });
  await chmod(path, 0o600);
  return true;
}

/**
 * Per-device sources (safari-<device>, helium-<device>) aren't listed in any
 * config file: each Mac creates its own folder in the shared sources-dir, so
 * the Mac that runs the indexer finds them there. Each gets a copy of its
 * per_device template's queries under its own name, so the index keeps
 * which Mac every visit came from.
 */
export async function deviceSources(sourcesDir = getSourcesDir()): Promise<TomlSource[]> {
  const cfg = await readSourcesToml();
  const known = new Set((cfg.sources ?? []).map((s) => s.name));
  const templates = (cfg.sources ?? []).filter((s) => s.per_device);
  let dirs: string[] = [];
  try {
    dirs = readdirSync(sourcesDir);
  } catch {
    return [];
  }
  const out: TomlSource[] = [];
  for (const t of templates) {
    for (const d of dirs.filter((d) => d.startsWith(`${t.name}-`)).sort()) {
      if (known.has(d) || !existsSync(join(sourcesDir, d, 'chronicle', 'chronicle.db'))) continue;
      const { per_device: _, ...rest } = t;
      out.push({ ...rest, name: d, enabled: true, db_path: `${d}/chronicle/chronicle.db` });
    }
  }
  return out;
}

/**
 * The indexer takes one config file. With a local overlay or per-device
 * sources, write repo + local + devices into
 * ~/.otso/config/sources.merged.toml (owner-only) and use that.
 */
export async function indexerConfigPath(sourcesDir = getSourcesDir()): Promise<string> {
  const local = getLocalSourcesPath();
  const devices = await deviceSources(sourcesDir);
  if (!existsSync(local) && !devices.length) return getSourcesTomlPath();
  const { mkdir, writeFile } = await import('node:fs/promises');
  await mkdir(getConfigDir(), { recursive: true, mode: 0o700 });
  const merged = join(getConfigDir(), 'sources.merged.toml');
  const parts = [
    '# Generated by otso from sources.toml + sources.local.toml + per-device sources. Do not edit.',
    await readFile(getSourcesTomlPath(), 'utf8'),
  ];
  if (existsSync(local)) parts.push(await readFile(local, 'utf8'));
  if (devices.length) parts.push(stringify({ sources: devices }));
  await writeFile(merged, parts.join('\n') + '\n', { mode: 0o600 });
  return merged;
}

/**
 * The indexer reads source databases from defaults.data_dir, which the
 * repo ships pointing at data/fixtures. Report it so `otso status` can say
 * when the indexer would ignore the real data the CLI writes.
 */
export async function configuredSourcesDir(path = getSourcesTomlPath()): Promise<string | null> {
  return (await readSourcesToml(path)).defaults?.data_dir ?? null;
}

